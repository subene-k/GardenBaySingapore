class AudioGuideController {
  private audioCtx: AudioContext | null = null;
  private isSpeaking: boolean = false;
  private currentUtterance: SpeechSynthesisUtterance | null = null;
  private chimeTimer: any = null;

  private initAudioContext() {
    if (!this.audioCtx) {
      const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
      if (AudioContextClass) {
        this.audioCtx = new AudioContextClass();
      }
    }
    if (this.audioCtx && this.audioCtx.state === 'suspended') {
      this.audioCtx.resume();
    }
  }

  // Play pleasant ambient botanical chime chords via Web Audio API
  private playIntroChime() {
    try {
      this.initAudioContext();
      if (!this.audioCtx) return;

      const now = this.audioCtx.currentTime;
      // Soft pentatonic botanical notes: C5 (523Hz), E5 (659Hz), G5 (784Hz), B5 (987Hz)
      const freqs = [523.25, 659.25, 783.99, 987.77];

      freqs.forEach((freq, idx) => {
        const osc = this.audioCtx!.createOscillator();
        const gain = this.audioCtx!.createGain();

        osc.type = 'sine';
        osc.frequency.setValueAtTime(freq, now + idx * 0.12);

        gain.gain.setValueAtTime(0, now + idx * 0.12);
        gain.gain.linearRampToValueAtTime(0.08, now + idx * 0.12 + 0.04);
        gain.gain.exponentialRampToValueAtTime(0.0001, now + idx * 0.12 + 1.2);

        osc.connect(gain);
        gain.connect(this.audioCtx!.destination);

        osc.start(now + idx * 0.12);
        osc.stop(now + idx * 0.12 + 1.3);
      });
    } catch (e) {
      console.warn('AudioContext chime error:', e);
    }
  }

  // Speak the curated docent audio guide
  public play(
    attractionId: string, 
    lang: SupportedLanguage, 
    onEndCallback?: () => void,
    onStartCallback?: () => void
  ) {
    this.stop();

    // Play pleasant intro chimes first
    this.playIntroChime();

    // Find script
    const scriptsForAttraction = AUDIO_TOUR_SCRIPTS[attractionId] || AUDIO_TOUR_SCRIPTS['flower-dome'];
    const textToSpeak = scriptsForAttraction[lang] || scriptsForAttraction['en'];

    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      // Delay speech slightly to let the botanical chime ring
      this.chimeTimer = setTimeout(() => {
        try {
          window.speechSynthesis.cancel();

          const utterance = new SpeechSynthesisUtterance(textToSpeak);
          this.currentUtterance = utterance;

          // Set language code
          if (lang === 'zh') utterance.lang = 'zh-CN';
          else if (lang === 'ms') utterance.lang = 'ms-MY';
          else if (lang === 'ta') utterance.lang = 'ta-IN';
          else utterance.lang = 'en-US';

          // Natural friendly docent pacing
          utterance.rate = 0.94;
          utterance.pitch = 1.02;

          utterance.onstart = () => {
            this.isSpeaking = true;
            if (onStartCallback) onStartCallback();
          };

          utterance.onend = () => {
            this.isSpeaking = false;
            if (onEndCallback) onEndCallback();
          };

          utterance.onerror = (err) => {
            console.warn('SpeechSynthesis error:', err);
            this.isSpeaking = false;
            if (onEndCallback) onEndCallback();
          };

          window.speechSynthesis.speak(utterance);
        } catch (err) {
          console.warn('speechSynthesis.speak failed:', err);
          if (onEndCallback) onEndCallback();
        }
      }, 400);
    } else {
      // If no speech synthesis in browser, stop after chime
      setTimeout(() => {
        if (onEndCallback) onEndCallback();
      }, 2500);
    }
  }

  public stop() {
    if (this.chimeTimer) {
      clearTimeout(this.chimeTimer);
      this.chimeTimer = null;
    }
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.cancel();
    }
    this.isSpeaking = false;
    this.currentUtterance = null;
  }
}

export const audioGuideService = new AudioGuideController();
